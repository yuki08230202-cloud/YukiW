def ts(t):
    return f"0:{t:02d}"


def cut(dur, place, act, lines, v=None, t=None, edit=""):
    c = {"dur": dur, "place": place, "act": act, "ref": ts(t) if v else "–", "edit": edit, "lines": lines}
